#!/usr/bin/env python3
"""Small synthetic inputs and quality oracle for #415; never a renderer.

Uses FFmpeg/ffprobe and the standard library. No network, services or originals.
Generated bytes are not promised identical across FFmpeg versions/platforms.
"""
import argparse
import array
import hashlib
import json
import math
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
RECIPE = ROOT / 'tests/fixtures/core-v2/stage-recipe-v1.json'
RATE = 16000
COLORS = {'red': (255, 0, 0), 'blue': (0, 0, 255),
          'green': (0, 128, 0), 'yellow': (255, 255, 0)}


def execute(args):
    result = subprocess.run(args, capture_output=True, timeout=180)
    if result.returncode:
        raise ValueError(f'{Path(args[0]).name} failed: '
                         + result.stderr.decode(errors='replace')[-1500:])
    return result.stdout


def probe(path):
    return json.loads(execute(['ffprobe', '-v', 'error', '-show_format',
                               '-show_streams', '-of', 'json', str(path)]))


def sha256(path):
    h = hashlib.sha256()
    with path.open('rb') as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def decode(path):
    # Both streams are mandatory, and any decoder error fails the check.
    execute(['ffmpeg', '-v', 'error', '-xerror', '-i', str(path), '-map', '0:v:0',
             '-map', '0:a:0', '-f', 'null', '-'])


def write_json_new(path, payload):
    with path.open('x', encoding='utf-8') as target:
        json.dump(payload, target, indent=2, sort_keys=True)
        target.write('\n')


def generate(destination):
    """Refuse overwrite; a failed run remains visibly incomplete, not certified."""
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=False, mode=0o700)
    recipe = json.loads(RECIPE.read_text())
    files = []
    for name, first, second, tone in [
        ('camera-a.mp4', 'red', 'green', 223),
        ('camera-b.mp4', 'blue', 'yellow', 443),
    ]:
        path = destination / name
        execute(['ffmpeg', '-nostdin', '-v', 'error', '-n', '-f', 'lavfi', '-i',
                 f'color=c={first}:s=640x360:r=30:d=6', '-f', 'lavfi', '-i',
                 f'sine=frequency={tone}:sample_rate=48000:duration=6',
                 '-vf', f"drawbox=c={second}:t=fill:enable='gte(t,3)'",
                 '-c:v', 'libx264', '-threads', '2', '-preset', 'ultrafast',
                 '-crf', '18', '-pix_fmt', 'yuv420p', '-c:a', 'aac',
                 '-movflags', '+faststart', '-shortest', str(path)])
        decode(path)
        files.append({'path': name, 'role': 'synthetic_camera',
                      'bytes': path.stat().st_size, 'sha256': sha256(path),
                      'first_color': first, 'after_3s_color': second,
                      'camera_tone_hz': tone})
    master = destination / 'master.wav'
    execute(['ffmpeg', '-nostdin', '-v', 'error', '-n', '-f', 'lavfi', '-i',
             'sine=frequency=997:sample_rate=48000:duration=6',
             '-c:a', 'pcm_s16le', str(master)])
    files.append({'path': master.name, 'role': 'synthetic_master',
                  'bytes': master.stat().st_size, 'sha256': sha256(master)})
    write_json_new(destination / 'recipe.json', recipe)
    files.append({'path': 'recipe.json', 'role': 'stage_v1_recipe',
                  'bytes': (destination / 'recipe.json').stat().st_size,
                  'sha256': sha256(destination / 'recipe.json')})
    manifest = {
        'schema': 'montara-jm-synthetic-fixture-1',
        'purpose': 'test inputs and oracle, not a V2 product schema',
        'ffmpeg': execute(['ffmpeg', '-version']).decode().splitlines()[0],
        'files': files,
        'expected': {
            'duration_sec': 6, 'duration_tolerance_sec': 0.15,
            'video_codec': 'h264', 'audio_codec': 'aac',
            # Native within-content bookends fade the first/last 1.5 seconds.
            # Sample outside those fades rather than loosening color tolerances.
            'frames': [{'at': 1.5, 'color': 'red'},
                       {'at': 2.25, 'color': 'blue'},
                       {'at': 2.8, 'color': 'yellow'},
                       {'at': 3.5, 'color': 'yellow'},
                       {'at': 4.5, 'color': 'green'}],
            'master_tone_hz': 997,
        },
    }
    # Manifest last: missing manifest means an incomplete generation.
    write_json_new(destination / 'fixture-manifest.json', manifest)
    return manifest


def verify_inputs(folder):
    folder = Path(folder)
    manifest_path = folder / 'fixture-manifest.json'
    if manifest_path.is_symlink():
        raise ValueError('Fixture manifest must be a regular file')
    manifest = json.loads(manifest_path.read_text())
    if manifest.get('schema') != 'montara-jm-synthetic-fixture-1':
        raise ValueError('Unknown fixture schema')
    files = manifest.get('files', [])
    if {r['path'] for r in files} != {'camera-a.mp4', 'camera-b.mp4',
                                    'master.wav', 'recipe.json'} or len(files) != 4:
        raise ValueError('Unexpected fixture files')
    for row in files:
        path = folder / row['path']
        if path.is_symlink() or not path.is_file():
            raise ValueError('Missing or nonregular fixture file: ' + row['path'])
        if path.stat().st_size != row['bytes'] or sha256(path) != row['sha256']:
            raise ValueError('Fixture integrity mismatch: ' + row['path'])
    if json.loads((folder / 'recipe.json').read_text()) != json.loads(RECIPE.read_text()):
        raise ValueError('Recipe is not the reviewed Stage v1 fixture')
    return manifest


def frame_color(path, at):
    raw = execute(['ffmpeg', '-v', 'error', '-ss', str(at), '-i', str(path),
                   '-frames:v', '1', '-vf', 'scale=1:1', '-pix_fmt', 'rgb24',
                   '-f', 'rawvideo', '-'])
    if len(raw) != 3:
        raise ValueError('Could not read expected frame')
    measured = tuple(raw)
    distances = {name: math.sqrt(sum((a-b)**2 for a, b in zip(measured, color)))
                 for name, color in COLORS.items()}
    name = min(distances, key=distances.get)
    if distances[name] > 80:
        raise ValueError(f'Unexpected frame color at {at}: {measured}')
    return name, measured


def tone_amplitude(samples, frequency):
    step = 2 * math.pi * frequency / RATE
    real = sum(value * math.cos(step * i) for i, value in enumerate(samples))
    imag = sum(value * math.sin(step * i) for i, value in enumerate(samples))
    return math.hypot(real, imag) / len(samples)


def verify_output(folder, output, *, width=1920, height=1080):
    """Check an output produced by the real renderer; never produce one here."""
    manifest = verify_inputs(folder)
    expected = manifest['expected']
    output = Path(output)
    if output.is_symlink() or not output.is_file():
        raise ValueError('Output must be an existing regular MP4')
    metadata = probe(output)
    videos = [s for s in metadata['streams'] if s['codec_type'] == 'video']
    audios = [s for s in metadata['streams'] if s['codec_type'] == 'audio']
    if len(videos) != 1 or len(audios) != 1:
        raise ValueError('Expected exactly one video and one audio stream')
    video, audio = videos[0], audios[0]
    if video['codec_name'] != expected['video_codec'] or audio['codec_name'] != expected['audio_codec']:
        raise ValueError('Expected H.264 and AAC')
    if (video['width'], video['height']) != (width, height):
        raise ValueError('Unexpected output resolution')
    duration = float(metadata['format']['duration'])
    if abs(duration - expected['duration_sec']) > expected['duration_tolerance_sec']:
        raise ValueError('Unexpected montage duration')
    decode(output)
    frames = []
    for sample in expected['frames']:
        color, rgb = frame_color(output, sample['at'])
        if color != sample['color']:
            raise ValueError(f'Wrong camera/source time at {sample["at"]}: {color}')
        frames.append({'at': sample['at'], 'color': color, 'rgb': rgb})
    tones = []
    for at in (1, 3, 5):
        raw = execute(['ffmpeg', '-v', 'error', '-ss', str(at), '-i', str(output),
                       '-t', '0.25', '-vn', '-ac', '1', '-ar', str(RATE),
                       '-f', 's16le', '-'])
        samples = array.array('h', raw)
        if sys.byteorder != 'little':
            samples.byteswap()
        if len(samples) < RATE // 8:
            raise ValueError('Missing audio at montage checkpoint')
        amplitudes = {hz: tone_amplitude(samples, hz) for hz in (223, 443, 997)}
        if amplitudes[997] < 50 or amplitudes[997] < 10 * max(amplitudes[223], amplitudes[443]):
            raise ValueError('Audio does not match the selected synthetic master')
        tones.append({'at': at, 'master_tone_hz': 997,
                      'amplitudes': {str(hz): round(a, 2) for hz, a in amplitudes.items()}})
    return {'status': 'PASS', 'scope': 'synthetic media quality only; not V2 E2E',
            'sha256': sha256(output), 'bytes': output.stat().st_size,
            'duration_sec': duration, 'width': width, 'height': height,
            'video_codec': video['codec_name'], 'audio_codec': audio['codec_name'],
            'full_decode': 'PASS', 'frames': frames, 'audio': tones}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    gen = sub.add_parser('generate')
    gen.add_argument('directory', type=Path)
    check = sub.add_parser('verify')
    check.add_argument('directory', type=Path)
    check.add_argument('output', type=Path)
    check.add_argument('--width', type=int, default=1920)
    check.add_argument('--height', type=int, default=1080)
    args = parser.parse_args()
    try:
        result = (generate(args.directory) if args.command == 'generate' else
                  verify_output(args.directory, args.output, width=args.width, height=args.height))
    except (ValueError, OSError, subprocess.TimeoutExpired) as exc:
        parser.exit(1, f'FAIL: {exc}\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
